public void tblInventory() {
    javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tblInventory.getModel();
    model.setRowCount(0);

    try {
        java.util.List<com.electrostore.model.Product> products = productController.getAllProducts();
        for (com.electrostore.model.Product p : products) {
            model.addRow(new Object[]{
                p.getProductId(),
                p.getProductCode(),
                p.getProductName(),
                p.getCategory(),
                String.format("%.2f", p.getUnitPrice()),
                p.getStockQuantity(),
                p.getSupplier()
            });
        }
    } catch (Exception ex) {
        javax.swing.JOptionPane.showMessageDialog(this, "Error loading inventory: " + ex.getMessage(), "Database Error", javax.swing.JOptionPane.ERROR_MESSAGE);
    }
}
