    private void btnEditProductActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditProductActionPerformed
        // TODO add your handling code here:
        int selectedRow = tblInventory.getSelectedRow();
    if (selectedRow == -1) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please select a product from the table to edit.", "No Selection", javax.swing.JOptionPane.WARNING_MESSAGE);
        return;
    }

   int productId = (int) tblInventory.getValueAt(selectedRow, 0);
    String code = tblInventory.getValueAt(selectedRow, 1).toString();
    String name = tblInventory.getValueAt(selectedRow, 2).toString();
    String category = tblInventory.getValueAt(selectedRow, 3).toString();
    double price = Double.parseDouble(tblInventory.getValueAt(selectedRow, 4).toString());
    int qty = Integer.parseInt(tblInventory.getValueAt(selectedRow, 5).toString());
    String supplier = tblInventory.getValueAt(selectedRow, 6) != null ? tblInventory.getValueAt(selectedRow, 6).toString() : "";

    com.electrostore.model.Product productToEdit = new com.electrostore.model.Product(productId, code, name, category, price, qty, supplier);

    DialogProductForm dialog = new DialogProductForm(this, true, productToEdit);
    dialog.setVisible(true);

    if (dialog.isSavedSuccessfully()) {
        tblInventory();
    
    
    }
    }//GEN-LAST:event_btnEditProductActionPerformed

    private void btnDeleteProductActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteProductActionPerformed
        // TODO add your handling code here:
       int selectedRow = tblInventory.getSelectedRow();
    if (selectedRow == -1) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please select a product to delete.", "No Selection", javax.swing.JOptionPane.WARNING_MESSAGE);
        return;
    }

      int productId = (int) tblInventory.getValueAt(selectedRow, 0);
    String productName = tblInventory.getValueAt(selectedRow, 2).toString();

    int confirm = javax.swing.JOptionPane.showConfirmDialog(
        this, 
        "Are you sure you want to delete product: " + productName + "?", 
        "Confirm Delete", 
        javax.swing.JOptionPane.YES_NO_OPTION, 
        javax.swing.JOptionPane.WARNING_MESSAGE
    );

    if (confirm == javax.swing.JOptionPane.YES_OPTION) {
         try {
            productController.deleteProduct(productId);
            javax.swing.JOptionPane.showMessageDialog(this, "Product deleted successfully!", "Success", javax.swing.JOptionPane.INFORMATION_MESSAGE);
            tblInventory();
        } catch (Exception ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error deleting product: " + ex.getMessage(), "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    
    }

        
    
    }//GEN-LAST:event_btnDeleteProductActionPerformed

    private void btnSearchInventoryActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchInventoryActionPerformed
        // TODO add your handling code here:
       String keyword = txtSearchInventory.getText().trim();
    if (keyword.isEmpty()) {
        tblInventory();
        return;
    }

    javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tblInventory.getModel();
    model.setRowCount(0);  

    try {
        java.util.List<com.electrostore.model.Product> products = productController.searchProducts(keyword);
        for (com.electrostore.model.Product p : products) {
            model.addRow(new Object[]{
                p.getProductId(),
                p.getProductCode(),
                p.getProductName(),
                p.getCategory(),
                String.format("%.2f", p.getUnitPrice()),
                p.getStockQuantity(),
                p.getSupplier()
            });
        }
    } catch (Exception ex) {
        javax.swing.JOptionPane.showMessageDialog(this, "Error searching products: " + ex.getMessage(), "Search Error", javax.swing.JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnSearchInventoryActionPerformed

